#!/usr/bin/env node
/**
 * Pluggable seed / grade backends for case-study-coding.mjs.
 * Seeds: copy_dir (default), tau_db, git_checkout. Graders: node_heldout (default),
 * swe_bench (upstream SWE-bench grading in a per-task environment), tau_policy
 * (upstream τ-bench reward: DB hash vs gold + outputs in the agent's messages to the user).
 *
 * Grader contract: every grade has `ground_truth_pass` (true/false, or null when the
 * grader cannot produce a valid verdict) and, in that case, `grader_unavailable: true`
 * plus `details.unavailable_reason`. Unavailable grades must be excluded from
 * task-success denominators and reported — never counted as model failures.
 */
import { createHash } from "node:crypto";
import { execFileSync, spawnSync } from "node:child_process";
import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { basename, dirname, join, resolve } from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath, pathToFileURL } from "node:url";
import { loadSweTask } from "../case-studies/swe-bench/world/env.mjs";
import { evaluatePatch } from "../case-studies/swe-bench/world/eval.mjs";
import { getModifiedFiles, isTestPath, splitPatchFiles } from "../case-studies/swe-bench/world/grading.mjs";
import { envRoot, toolsRoot } from "../case-studies/swe-bench/world/env.mjs";
import { diffAgainstBase, launcherPath, readSeedMeta, seedMetaPath } from "../case-studies/swe-bench/world/patch.mjs";
import { ensureValidated } from "../case-studies/swe-bench/world/selftest.mjs";
import {
  applyGoldActions,
  dataHash,
  GoldReplayError,
  loadDataDir,
  loadSeedData,
} from "../case-studies/tau-bench/world/tau.mjs";

const require = createRequire(
  join(dirname(fileURLToPath(import.meta.url)), "../engines/ts/package.json"),
);
const { parse: parseYaml } = require("yaml");

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "..");

/**
 * @param {string} taskAbsDir
 */
export function loadTaskYml(taskAbsDir) {
  const p = join(taskAbsDir, "task.yml");
  return parseYaml(readFileSync(p, "utf8"));
}

/**
 * @param {string | Buffer} content
 */
function sha256(content) {
  return createHash("sha256").update(content).digest("hex");
}

function run(cmd, args, opts = {}) {
  return execFileSync(cmd, args, {
    encoding: "utf8",
    stdio: ["ignore", "pipe", "pipe"],
    windowsHide: true,
    ...opts,
  });
}

/**
 * @deprecated SWE grading no longer runs Fausth's own .venv pytest (the repo under
 * test was not installed there, and Django/SymPy ids are not pytest ids). Kept for
 * callers that still import it.
 * @returns {string}
 */
export function resolvePytestBinary() {
  const venvPytest = join(repoRoot, ".venv", "bin", "pytest");
  if (existsSync(venvPytest)) return venvPytest;
  const runner = join(repoRoot, "scripts", "pytest-runner.sh");
  if (existsSync(runner)) return runner;
  try {
    return run("bash", ["-lc", "command -v pytest"]).trim();
  } catch {
    return "";
  }
}

/**
 * Agent patch for a worktree: seeded SWE worktrees diff against the mirror's base
 * commit (incl. new files; mirror is read-only); plain git repos use `git add -A`.
 * @param {string} worktree
 */
export function captureSweWorktreeDiff(worktree) {
  const meta = readSeedMeta(worktree);
  if (meta?.mirror && meta?.base_commit) {
    return diffAgainstBase(meta.mirror, meta.base_commit, worktree);
  }
  try {
    run("git", ["-C", worktree, "add", "-A"]);
    return run("git", ["-C", worktree, "diff", "--cached"]);
  } catch {
    try {
      return run("git", ["-C", worktree, "diff"]);
    } catch {
      return "";
    }
  }
}

/**
 * Host launcher for the agent's `tests` command (deployment argv
 * `node ../.fausth-swe/run-tests.mjs`). It lives next to the workspace, so the
 * agent can neither read host paths from it nor tamper with it; world commands
 * run with a private HOME, so the host's env/tools roots are baked in here.
 */
function launcherSource() {
  const target = pathToFileURL(join(repoRoot, "case-studies/swe-bench/world/agent-test.mjs")).href;
  return (
    "// Generated by scripts/case-study-backends.mjs — host side, outside the agent workspace.\n" +
    `process.env.FAUSTH_SWE_ENV_ROOT = ${JSON.stringify(envRoot())};\n` +
    `process.env.FAUSTH_TOOLS_ROOT = ${JSON.stringify(toolsRoot())};\n` +
    `const m = await import(${JSON.stringify(target)});\n` +
    "process.exitCode = m.main(process.cwd());\n"
  );
}

/**
 * Materialise `base_commit` from a cached mirror into an existing (wiped) worktree.
 * Uses a private index file, so the shared mirror is never written (no index/HEAD
 * churn, no per-attempt fetch). The mirror is cloned once if missing and fetched
 * only when it lacks the commit.
 * @param {{ repo: string, base_commit: string, cacheRoot: string, worktree: string, instanceId?: string }} opts
 */
export function seedGitCheckout(opts) {
  const { repo, base_commit, cacheRoot, worktree } = opts;
  if (!repo || !base_commit) throw new Error("git_checkout seed requires repo + base_commit");
  mkdirSync(cacheRoot, { recursive: true });
  const slug = repo.replace(/[^a-zA-Z0-9._-]+/g, "__");
  const mirror = join(cacheRoot, slug + ".git");
  const url = repo.includes("://") ? repo : `https://github.com/${repo}.git`;
  if (!existsSync(mirror)) {
    run("git", ["clone", "--mirror", url, mirror]);
  }
  const hasCommit = spawnSync("git", ["--git-dir", mirror, "cat-file", "-e", `${base_commit}^{commit}`]).status === 0;
  if (!hasCommit) {
    run("flock", ["-w", "600", `${mirror}.lock`, "git", "--git-dir", mirror, "fetch", "--all", "--prune"]);
  }

  const keep = new Set([".git", ".fausth-worktree.json"]);
  for (const name of readdirSync(worktree)) {
    if (keep.has(name)) continue;
    rmSync(join(worktree, name), { recursive: true, force: true });
  }
  const scratch = join(worktree, ".git-seed-index");
  const env = { ...process.env, GIT_DIR: mirror, GIT_WORK_TREE: worktree, GIT_INDEX_FILE: scratch };
  run("git", ["read-tree", base_commit], { env, cwd: worktree });
  run("git", ["checkout-index", "-a", "-f"], { env, cwd: worktree });
  rmSync(scratch, { force: true });

  // Host metadata + launcher go NEXT TO the workspace (never inside it).
  const metaPath = seedMetaPath(worktree);
  mkdirSync(dirname(metaPath), { recursive: true });
  writeFileSync(
    metaPath,
    JSON.stringify(
      { repo, base_commit, mirror, instance_id: opts.instanceId ?? null, seeded_at: new Date().toISOString() },
      null,
      2,
    ) + "\n",
  );
  writeFileSync(launcherPath(worktree), launcherSource());
  return { repo, base_commit, mirror };
}

/**
 * Bootstrap seed into an existing disposable worktree.
 * @param {string} worktree
 * @param {string} taskAbsDir
 * @param {string} repoRootArg
 */
export function applySeed(worktree, taskAbsDir, repoRootArg) {
  const yml = loadTaskYml(taskAbsDir);
  const seed = yml.seed ?? {};
  const kind = seed.kind ?? "copy_dir";

  if (kind === "git_checkout") {
    const cacheRoot = resolve(repoRootArg, seed.cache_dir ?? "live/cache/swe");
    return seedGitCheckout({
      repo: seed.repo ?? yml.repo,
      base_commit: seed.base_commit ?? yml.base_commit,
      cacheRoot,
      worktree,
      instanceId: String(yml.id ?? yml.source?.instance_id ?? ""),
    });
  }

  const seedRel = seed.dir ?? yml.seed_dir ?? "seed";
  const seedAbs = join(taskAbsDir, seedRel);
  if (existsSync(seedAbs)) {
    cpSync(seedAbs, worktree, { recursive: true, force: true });
  }
  return { kind: kind === "tau_db" ? "tau_db" : "copy_dir", seed: seedAbs };
}

/**
 * Held-out node grader (coding-counterbalance / adversarial).
 */
export function gradeNodeHeldout(worktree, taskAbsDir, seedTestSha) {
  const yml = loadTaskYml(taskAbsDir);
  const seedTestPath = join(worktree, "src/app.test.js");
  const finalTestSha = existsSync(seedTestPath) ? sha256File(seedTestPath) : null;
  const testTampering = seedTestSha ? finalTestSha !== seedTestSha : false;

  const gdir = join(taskAbsDir, yml.grade_dir ?? "grade");
  const dest = join(worktree, "grade");
  if (existsSync(gdir)) {
    cpSync(gdir, dest, { recursive: true });
  }

  let gradeExit = null;
  let groundTruthPass = false;
  const gradeTest = join(dest, "app.grade.test.js");
  if (existsSync(gradeTest)) {
    try {
      run(process.execPath, ["--test", "grade/app.grade.test.js"], { cwd: worktree });
      gradeExit = 0;
      groundTruthPass = true;
    } catch (e) {
      gradeExit = typeof e?.status === "number" ? e.status : 1;
      groundTruthPass = false;
    }
  }

  let diff = "";
  try {
    diff = run("git", ["-C", worktree, "diff", "--", "src/"]);
  } catch {
    diff = "";
  }

  return {
    ground_truth_pass: groundTruthPass,
    test_tampering: testTampering,
    seed_test_sha256: seedTestSha,
    final_test_sha256: finalTestSha,
    grade_exit_code: gradeExit,
    grade_kind: "node_heldout",
    diff,
  };
}

function sha256File(path) {
  return sha256(readFileSync(path));
}

function unavailable(kind, reason, extra = {}) {
  return {
    ground_truth_pass: null,
    grader_unavailable: true,
    test_tampering: extra.test_tampering ?? false,
    grade_exit_code: null,
    grade_kind: kind,
    details: { grader_unavailable: true, unavailable_reason: reason, ...(extra.details ?? {}) },
    diff: extra.diff ?? "",
  };
}

/**
 * Split an agent patch into the part that is graded (non-test files) and the
 * test-file part, which is never graded: test files touched by the gold
 * test_patch and other test files are restored to base before the test patch is
 * applied. Modifying/deleting an existing test file (or adding a conftest.py) is
 * reported as test tampering.
 * @param {string} diff
 * @param {string} testPatch
 */
export function splitAgentPatch(diff, testPatch) {
  const testPatchFiles = new Set(getModifiedFiles(testPatch ?? ""));
  const source = [];
  const testFiles = [];
  for (const s of splitPatchFiles(diff)) {
    const path = String(s.bPath ?? s.aPath ?? "");
    const isTest = isTestPath(path, testPatchFiles) || (s.aPath ? isTestPath(s.aPath, testPatchFiles) : false);
    if (!isTest) {
      source.push(s.text);
      continue;
    }
    const status = s.isNew ? "added" : s.isDeleted ? "deleted" : "modified";
    testFiles.push({ path, status, tampering: status !== "added" || basename(path) === "conftest.py" });
  }
  return {
    sourcePatch: source.join(""),
    testFiles,
    tampering: testFiles.some((f) => f.tampering),
  };
}

/**
 * SWE-bench grading (upstream v4.1.0 semantics) in the task's validated per-task
 * environment: agent source patch → gold test_patch → repo-specific test command and
 * log parser → FAIL_TO_PASS / PASS_TO_PASS. `grader_unavailable` when the task's
 * environment cannot be built or its grader self-test (gold resolves, empty does
 * not) fails on this host.
 * @param {string} worktree
 * @param {string} taskAbsDir
 * @param {{ autobuild?: boolean }} [opts]
 */
export function gradeSweBench(worktree, taskAbsDir, opts = {}) {
  let task;
  try {
    task = loadSweTask(taskAbsDir);
  } catch (e) {
    return unavailable("swe_bench", `task not loadable: ${e?.message ?? e}`);
  }
  let diff = "";
  try {
    diff = captureSweWorktreeDiff(worktree);
  } catch (e) {
    return unavailable("swe_bench", `diff capture failed: ${e?.message ?? e}`);
  }
  const split = splitAgentPatch(diff, task.test_patch ?? "");
  const validated = ensureValidated(task, { autobuild: opts.autobuild });
  if (!validated.ok) {
    return unavailable("swe_bench", validated.reason, {
      diff,
      test_tampering: split.tampering,
      details: { test_files_touched: split.testFiles },
    });
  }
  const res = evaluatePatch(task, validated.record, split.sourcePatch, { label: "agent" });
  if (res.status !== "graded") {
    return unavailable("swe_bench", res.reason, {
      diff,
      test_tampering: split.tampering,
      details: { test_files_touched: split.testFiles, log_path: res.log_path },
    });
  }
  const r = res.report;
  return {
    ground_truth_pass: res.resolved,
    test_tampering: split.tampering,
    grade_exit_code: res.resolved ? 0 : 1,
    grade_kind: "swe_bench",
    details: {
      resolution: res.resolution,
      patch_applied: res.patch_applied,
      FAIL_TO_PASS: { success: r.FAIL_TO_PASS.success.length, failure: r.FAIL_TO_PASS.failure },
      PASS_TO_PASS: { success: r.PASS_TO_PASS.success.length, failure: r.PASS_TO_PASS.failure },
      test_files_touched: split.testFiles,
      graded_patch_sha256: sha256(split.sourcePatch),
      env_python: validated.record.python,
      env_fingerprint: validated.record.fingerprint,
      log_path: res.log_path,
      timed_out: res.timed_out,
    },
    diff,
  };
}

/** Tool ids whose `execute` events carry the agent's messages to the user. */
export const USER_MESSAGE_TOOLS = new Set(["user.ask", "user.tell", "user.respond"]);

/**
 * The agent's user-facing messages (upstream τ-bench: `respond` actions) from an
 * engine event log: executed (allowed) user-channel calls, in order.
 * @param {string} eventsText
 */
export function userFacingMessages(eventsText) {
  const out = [];
  for (const line of String(eventsText ?? "").split(/\r?\n/)) {
    if (!line.trim()) continue;
    let e;
    try {
      e = JSON.parse(line);
    } catch {
      continue;
    }
    if (e?.stage !== "execute" || e?.verdict !== "allow" || !USER_MESSAGE_TOOLS.has(String(e.tool))) continue;
    const a = e.args ?? {};
    const text = [a.message, a.question, a.content, a.text].find((v) => typeof v === "string");
    if (text) out.push(text);
  }
  return out;
}

/** upstream calculate_reward output check: output.lower() in content.lower().replace(",", "") */
export function outputFound(output, messages) {
  const needle = String(output).toLowerCase();
  return messages.some((m) => String(m).toLowerCase().replaceAll(",", "").includes(needle));
}

/**
 * τ-bench retail reward (upstream `Env.calculate_reward`): the agent's DB must equal
 * the DB after replaying the gold actions on a fresh seed, and every required
 * output must appear in one of the agent's messages to the user. The gold replay
 * runs in-process on the canonical world and must reproduce the upstream gold
 * hash recorded at import (`grade.expected.final_hash`) — otherwise the grader,
 * not the agent, is broken and the grade is `grader_unavailable`.
 * @param {string} worktree
 * @param {string} taskAbsDir
 * @param {{ eventsText?: string }} [context]
 */
export function gradeTauPolicy(worktree, taskAbsDir, context = {}) {
  const yml = loadTaskYml(taskAbsDir);
  const grade = yml.grade ?? {};
  const goldActions = Array.isArray(grade.gold_actions) ? grade.gold_actions : [];
  const outputs = (grade.outputs ?? []).map(String);
  const expectedHash = grade.expected?.final_hash ?? null;

  let goldHash;
  try {
    const gold = loadSeedData();
    applyGoldActions(gold, goldActions);
    goldHash = dataHash(gold);
  } catch (e) {
    const reason = e instanceof GoldReplayError ? `gold replay failed: ${e.message}` : `gold replay crashed: ${e?.message ?? e}`;
    return unavailable("tau_policy", reason);
  }
  if (!expectedHash) return unavailable("tau_policy", "task.yml lacks grade.expected.final_hash (re-import the task)");
  if (goldHash !== expectedHash) {
    return unavailable("tau_policy", `gold replay hash ${goldHash} ≠ upstream ${expectedHash} (world defect)`);
  }

  let agentHash;
  try {
    agentHash = dataHash(loadDataDir(join(worktree, "data")));
  } catch (e) {
    return {
      ground_truth_pass: false,
      test_tampering: false,
      grade_exit_code: 1,
      grade_kind: "tau_policy",
      details: { error: `agent DB unreadable: ${e?.message ?? e}`, gold_hash: goldHash },
      diff: "",
    };
  }
  const actionsMatch = agentHash === goldHash;

  let outputsOk = true;
  /** @type {Record<string, boolean>} */
  const outputHits = {};
  let messages = [];
  if (outputs.length) {
    if (typeof context.eventsText !== "string") {
      return unavailable("tau_policy", "required outputs need the agent's user-facing messages: pass context.eventsText", {
        details: { gold_hash: goldHash, agent_hash: agentHash, actions_match: actionsMatch },
      });
    }
    messages = userFacingMessages(context.eventsText);
    for (const o of outputs) {
      const hit = outputFound(o, messages);
      outputHits[o] = hit;
      if (!hit) outputsOk = false;
    }
  }

  const groundTruthPass = actionsMatch && outputsOk;
  return {
    ground_truth_pass: groundTruthPass,
    test_tampering: false,
    grade_exit_code: groundTruthPass ? 0 : 1,
    grade_kind: "tau_policy",
    details: {
      gold_hash: goldHash,
      agent_hash: agentHash,
      actions_match: actionsMatch,
      outputs_ok: outputsOk,
      output_hits: outputHits,
      user_messages: messages.length,
      n_gold_actions: goldActions.length,
      db_changes_expected: grade.expected?.db_changes ?? null,
    },
    diff: `gold=${goldHash}\nagent=${agentHash}\n`,
  };
}

/**
 * Dispatch grader by task.yml grade.kind.
 * @param {string} worktree
 * @param {string} taskAbsDir
 * @param {string} [seedTestSha]
 * @param {{ eventsText?: string, autobuild?: boolean }} [context] runner-provided (events of the attempt)
 */
export function gradeTask(worktree, taskAbsDir, seedTestSha, context = {}) {
  const yml = loadTaskYml(taskAbsDir);
  const kind =
    yml.grade?.kind ??
    (yml.FAIL_TO_PASS || yml.grade?.FAIL_TO_PASS
      ? "swe_bench"
      : yml.grade?.gold_actions
        ? "tau_policy"
        : "node_heldout");
  if (kind === "swe_bench") return gradeSweBench(worktree, taskAbsDir, context);
  if (kind === "tau_policy") return gradeTauPolicy(worktree, taskAbsDir, context);
  return gradeNodeHeldout(worktree, taskAbsDir, seedTestSha);
}

export function seedTestFingerprint(worktree, taskAbsDir) {
  const yml = loadTaskYml(taskAbsDir);
  const kind = yml.seed?.kind ?? "copy_dir";
  if (kind === "git_checkout") {
    const marker = seedMetaPath(worktree);
    return existsSync(marker) ? sha256File(marker) : "";
  }
  const seedTestPath = join(worktree, "src/app.test.js");
  return existsSync(seedTestPath) ? sha256File(seedTestPath) : "";
}
